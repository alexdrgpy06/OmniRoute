export interface ExistingCombo {
  id: string;
  name: string;
  strategy?: string;
  models?: unknown[];
  config?: Record<string, unknown> | null;
}

export interface CockpitComboDiff {
  create: CockpitCombo[];
  update: Array<{ id: string; combo: CockpitCombo }>;
  unchanged: string[];
  /** Existing cockpit-* combos the current data no longer produces (reported, never deleted). */
  stale: string[];
}

function canonicalStep(step: unknown): string {
  if (typeof step === "string") return JSON.stringify({ kind: "model", model: step });
  const s = (step ?? {}) as Record<string, unknown>;
  if (s.kind === "combo-ref") return JSON.stringify({ kind: "combo-ref", comboName: s.comboName });
  const allowed = Array.isArray(s.allowedConnectionIds)
    ? [...(s.allowedConnectionIds as string[])].sort()
    : [];
  return JSON.stringify({ kind: "model", model: s.model, allowed });
}

function sameCombo(generated: CockpitCombo, existing: ExistingCombo): boolean {
  if ((existing.strategy || "priority") !== generated.strategy) return false;
  const a = generated.models.map(canonicalStep);
  const b = (existing.models ?? []).map(canonicalStep);
  if (a.length !== b.length || a.some((v, i) => v !== b[i])) return false;
  const cfg = existing.config ?? {};
  return Object.entries(generated.config).every(
    ([key, value]) => JSON.stringify(cfg[key]) === JSON.stringify(value)
  );
}

export function diffCockpitCombos(
  generated: CockpitCombo[],
  existing: ExistingCombo[]
): CockpitComboDiff {
  const existingByName = new Map(existing.map((c) => [c.name, c]));
  const diff: CockpitComboDiff = { create: [], update: [], unchanged: [], stale: [] };
  for (const combo of generated) {
    const current = existingByName.get(combo.name);
    if (!current) diff.create.push(combo);
    else if (sameCombo(combo, current)) diff.unchanged.push(combo.name);
    else diff.update.push({ id: current.id, combo });
  }
  const generatedNames = new Set(generated.map((c) => c.name));
  for (const c of existing) {
    if (c.name.startsWith(COCKPIT_COMBO_PREFIX) && !generatedNames.has(c.name)) {
      diff.stale.push(c.name);
    }
  }
  return diff;
}
